#!/usr/bin/env python3
"""Validate that the full Alembic migration chain applies to an empty database.

Creates a throwaway database (otix_migrate_check), applies ``alembic upgrade
head`` to it, and exits non-zero if anything fails. This catches broken
migrations — like the autogenerated rebuild that previously sat in the chain —
before they ever reach a real environment.

The database named in DATABASE_URL_SYNC is never touched; it is only used as
the admin connection to create the check database.

Usage (run from backend/):
    DATABASE_URL_SYNC=postgresql://user:pass@host:5432/admin_db \
        python scripts/migrate-check.py
"""
from __future__ import annotations

import os
import sys
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

import psycopg2

CHECK_DB = "otix_migrate_check"
MAINTENANCE_DB = "postgres"


def main() -> int:
    sync_url = os.environ.get("DATABASE_URL_SYNC", "")
    if not sync_url:
        print(
            "error: DATABASE_URL_SYNC must be set, e.g. "
            "postgresql://user:pass@host:5432/admin_db",
            file=sys.stderr,
        )
        return 2

    if os.environ.get("APP_ENV") == "production":
        print(
            "error: refusing to run the migration check against production "
            "(APP_ENV=production)",
            file=sys.stderr,
        )
        return 2

    parts = urlsplit(sync_url)
    if not parts.scheme.startswith("postgresql"):
        print(f"error: expected a postgresql:// URL, got: {parts.scheme}", file=sys.stderr)
        return 2

    # Connect to the maintenance DB so we can DROP/CREATE the check database
    # without touching the database named in the URL.
    admin_parts = parts._replace(path=f"/{MAINTENANCE_DB}")
    conn = psycopg2.connect(urlunsplit(admin_parts))
    conn.autocommit = True
    with conn.cursor() as cur:
        cur.execute(f"DROP DATABASE IF EXISTS {CHECK_DB} WITH (FORCE)")
        cur.execute(f"CREATE DATABASE {CHECK_DB}")
    conn.close()

    os.environ["DATABASE_URL_SYNC"] = urlunsplit(parts._replace(path=f"/{CHECK_DB}"))

    from alembic import command
    from alembic.config import Config

    ini = Path(__file__).resolve().parents[1] / "alembic.ini"
    cfg = Config(str(ini))
    cfg.set_main_option("sqlalchemy.url", os.environ["DATABASE_URL_SYNC"])

    print(f">>> Applying Alembic chain to fresh database '{CHECK_DB}'...")
    command.upgrade(cfg, "head")
    print(">>> Migration chain applies cleanly to an empty database.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
